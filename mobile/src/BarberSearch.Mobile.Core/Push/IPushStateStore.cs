namespace BarberSearch.Mobile.Core.Push;

/// <summary>
/// Локальное состояние push: выбор человека и последний зарегистрированный токен.
/// </summary>
/// <remarks>
/// <para>
/// Метка токена нужна, чтобы снять устройство с регистрации при выходе: токен живёт в FCM,
/// а сервер знает его только по последнему <c>POST api/push/devices</c>, и без метки клиенту
/// нечего отправить в <c>unregister</c>. Хранилище — настройки платформы (реализация в
/// приложении), поэтому Core знает только интерфейс.
/// </para>
/// <para>
/// Переключатель по умолчанию включён: напоминания — часть записи, а не отдельная услуга,
/// и человек выключает их осознанно. Ошибка чтения или записи настроек не роняет экран —
/// значение остаётся в памяти до перезапуска, как у языка и темы.
/// </para>
/// </remarks>
public interface IPushStateStore
{
    /// <summary>
    /// Включил ли человек напоминания; по умолчанию <c>true</c>.
    /// </summary>
    bool IsEnabled { get; }

    /// <summary>
    /// Запоминает выбор человека.
    /// </summary>
    /// <param name="enabled">Новое значение переключателя.</param>
    void SetEnabled(bool enabled);

    /// <summary>
    /// Токен, последним успешно отправленный на сервер, либо <c>null</c>.
    /// </summary>
    string? RegisteredToken { get; }

    /// <summary>
    /// Запоминает токен после успешной регистрации или стирает метку.
    /// </summary>
    /// <param name="token">Токен либо <c>null</c>, чтобы стереть метку.</param>
    void SetRegisteredToken(string? token);
}
