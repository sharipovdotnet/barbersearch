using BarberSearch.Contracts.Users.Me;
using BarberSearch.Mobile.Core.Media;

namespace BarberSearch.Mobile.Core.Api.Account;

/// <summary>
/// Аватар текущего пользователя: чтение профиля, загрузка и удаление кадра.
/// </summary>
/// <remarks>
/// <para>
/// Аватар принадлежит агрегату пользователя, а не профилю барбера: чтение идёт через
/// <c>GET api/users/me</c>, а загрузка и удаление — через <c>POST</c> и
/// <c>DELETE api/users/me/avatar</c>. Отдельного <c>GET api/users/me/avatar</c> нет: состояние
/// кадра приходит частью профиля. У барбера это фото открытой карточки, а не работа
/// портфолио (<c>api/barber-profiles/{id}/photos</c>): удаление аватара не трогает
/// портфолио, а загрузка нового кадра не добавляет работу. Идентификатор пользователя
/// сервер берёт из access-токена, поэтому чужой аватар загрузить или удалить нечем — в
/// запросах нет ни <c>userId</c>, ни ссылки на профиль барбера.
/// </para>
/// <para>
/// Загрузка проходит премодерацию: любой принятый файл создаётся в статусе <c>Pending</c> и
/// публично не виден до одобрения администратором. Владелец видит его в кабинете как превью
/// с бейджем «На проверке», карточка барбера до одобрения показывает прежний кадр либо
/// инициалы. Поэтому <see cref="UploadAvatarAsync"/> возвращает не только адрес файла, но и
/// состояние проверки: статус нужно показать сразу, не дожидаясь повторного чтения профиля.
/// </para>
/// <para>
/// <see cref="GetMyProfileAsync"/> нужен отдельно: публичная карточка барбера скрывает
/// неодобренный аватар, подменяя ссылку на <c>null</c>, и не отдаёт статус проверки. Кабинет
/// же обязан показать владельцу собственный кадр вместе с <c>IsAvatarBlocked</c>,
/// <c>AvatarModerationStatus</c> и причиной отказа — эти поля есть только в
/// <c>GET api/users/me</c>. Сырой <c>AvatarUrl</c> оттуда приходит даже для скрытого кадра,
/// чтобы сохранение имени не стёрло файл.
/// </para>
/// </remarks>
public interface IAccountAvatarApi
{
    /// <summary>
    /// Читает профиль текущего пользователя вместе с состоянием аватара.
    /// </summary>
    /// <remarks>
    /// Ходит на <c>GET api/users/me</c>, а не на <c>GET api/users/me/avatar</c>: отдельного
    /// читаемого ответа у аватара нет, он всегда приходит частью профиля. Карточка барбера
    /// для этого не годится — она маскирует неодобренный кадр в <c>null</c> и не раскрывает
    /// статус модерации, поэтому кабинет читает профиль из базы.
    /// </remarks>
    /// <param name="cancellationToken">Токен отмены.</param>
    /// <returns>Профиль из базы с полями модерации аватара.</returns>
    Task<MyProfileResponse> GetMyProfileAsync(CancellationToken cancellationToken = default);

    /// <summary>
    /// Загружает новый аватар текущего пользователя.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <c>POST api/users/me/avatar</c> принимает <c>multipart/form-data</c> с единственной
    /// частью <c>file</c>. Успех — <c>201</c> с относительным адресом сохранённого файла и
    /// статусом <c>Pending</c>: кадр премодерируется, поэтому публично он появится только
    /// после одобрения.
    /// </para>
    /// <para>
    /// Файл готовит приложение: Core отправляет уже перекодированный JPEG, а сервер повторно
    /// проверяет сигнатуру, стороны и размер теми же правилами, что и портфолио.
    /// </para>
    /// </remarks>
    /// <param name="image">Подготовленный файл: байты, имя части и MIME-тип.</param>
    /// <param name="cancellationToken">Токен отмены.</param>
    /// <returns>Адрес сохранённого файла и состояние проверки.</returns>
    Task<AvatarUploadResponse> UploadAvatarAsync(
        PortfolioImage image,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Удаляет аватар текущего пользователя.
    /// </summary>
    /// <remarks>
    /// <c>DELETE api/users/me/avatar</c> идемпотентен: <c>204</c> приходит и тогда, когда
    /// аватара не было. Успех — отсутствие ошибки, тело не читается. Файл после удаления не
    /// восстановить: вернуть прежний кадр может только администратор.
    /// </remarks>
    /// <param name="cancellationToken">Токен отмены.</param>
    Task DeleteAvatarAsync(CancellationToken cancellationToken = default);
}
