namespace BarberSearch.Mobile.Core.Api;

/// <summary>
/// Чем закончился запрос к API — с точки зрения решения «показывать ошибку, повторять или
/// молчать».
/// </summary>
/// <remarks>
/// Экраны больше не разбирают исключения по типам: один классификатор сводит их к этому
/// перечислению, а цикл повторов и текст ошибки принимают решение по одному значению. Три
/// сбоя — это три разных поведения для человека: «нет связи», «сервер просит подождать» и
/// окончательный отказ, который бессмысленно повторять.
/// </remarks>
public enum ApiFailureKind
{
    /// <summary>
    /// Сбоя нет: запрос не падал, либо его отменил сам экран.
    /// </summary>
    /// <remarks>
    /// Отмена отличается от ошибки намеренно: если человек ушёл с экрана или нажал «Отмена»,
    /// показывать сообщение нельзя — он не ждёт ответа.
    /// </remarks>
    None = 0,

    /// <summary>
    /// Ответа не было вовсе: DNS, TCP, TLS, оборванное соединение или таймаут <c>HttpClient</c>.
    /// </summary>
    /// <remarks>
    /// Для человека это «нет связи с сервером»: следующий запрос может уйти, когда сеть
    /// вернётся, поэтому повтор осмыслен. Под этот вид попадает и таймаут клиента: он
    /// выбрасывается как <see cref="TaskCanceledException"/>, но отмены не было.
    /// </remarks>
    Transport,

    /// <summary>
    /// Сервер ответил, но ответ обещает, что повтор может помочь: <c>5xx</c>, <c>408</c>,
    /// <c>429</c>.
    /// </summary>
    /// <remarks>
    /// Это не «нет связи» и не окончательный отказ: сервер жив, но временно не может
    /// обслужить запрос или просит сбавить темп. Человеку показывается соответствующая
    /// причина, а цикл повторяет запрос с нарастающей паузой.
    /// </remarks>
    RetryableServer,

    /// <summary>
    /// Ответ окончательный: повтор лишь повторит отказ (<c>400</c>, <c>401</c>, <c>403</c>,
    /// <c>404</c>, <c>409</c> и всё незнакомое).
    /// </summary>
    /// <remarks>
    /// Повторять бессмысленно: сервер уже сказал «нет», и следующий запрос придёт с тем же
    /// телом и получит тот же ответ. Незнакомое исключение тоже считается окончательным:
    /// повторять неизвестный сбой вслепую — значит прятать его от экрана.
    /// </remarks>
    Terminal,
}
