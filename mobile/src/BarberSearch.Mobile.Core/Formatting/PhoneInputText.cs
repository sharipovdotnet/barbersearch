using BarberSearch.Mobile.Core.Localization;

namespace BarberSearch.Mobile.Core.Formatting;

/// <summary>
/// Текст отказа телефона, общий для всех форм с российским мобильным номером.
/// </summary>
/// <remarks>
/// <para>
/// Одно и то же правило проверяет сервер (<c>PhoneNumber</c> в домене) для профиля, телефона
/// гостя и салона, поэтому и объяснение у поля одно: «Личные данные», «Записать клиента» и
/// «Создать салон» показывают этот текст, а не три его копии.
/// </para>
/// <para>
/// Строка проходит через <see cref="Loc.T(string)"/>, как и остальные тексты приложения,
/// поэтому английский каталог покрывает все три формы сразу.
/// </para>
/// </remarks>
public static class PhoneInputText
{
    /// <summary>
    /// Номер не является российским мобильным: не хватает цифр, чужой код страны или
    /// городской диапазон.
    /// </summary>
    public static string Invalid =>
        Loc.T("Похоже, в номере опечатка. Нужен российский мобильный номер, например +7 900 000-00-00.");
}
