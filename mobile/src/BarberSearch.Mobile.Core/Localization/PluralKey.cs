namespace BarberSearch.Mobile.Core.Localization;

/// <summary>
/// Смысловые ключи счётчиков.
/// </summary>
/// <remarks>
/// Ключ — единица счёта, а не русская строка: одна и та же единица встречается в разных
/// предложениях («3 отзыва», «через 3 дня»), и её формы не должны дублироваться. Набор
/// повторяет <c>frontend/src/i18n/plurals.ts</c> в той части, которая нужна телефону.
/// </remarks>
public enum PluralKey
{
    /// <summary>
    /// Отзывы: «1 отзыв», «2 отзыва», «5 отзывов».
    /// </summary>
    Reviews,

    /// <summary>
    /// Стаж: «1 год», «2 года», «8 лет».
    /// </summary>
    Experience,

    /// <summary>
    /// Минуты обратного отсчёта: «через 1 минуту».
    /// </summary>
    Minutes,

    /// <summary>
    /// Часы обратного отсчёта: «через 2 часа».
    /// </summary>
    Hours,

    /// <summary>
    /// Дни обратного отсчёта: «через 3 дня».
    /// </summary>
    Days,

    /// <summary>
    /// Счётчик найденных мастеров: «Показан 1 мастер», «Показаны 2 мастера».
    /// </summary>
    ShownBarbers,

    /// <summary>
    /// Профили мастеров в админской сводке: «1 профиль», «2 профиля», «5 профилей».
    /// </summary>
    Profiles,

    /// <summary>
    /// Заявки «Стать мастером» в админской сводке: «1 заявка», «2 заявки», «5 заявок».
    /// </summary>
    Requests,

    /// <summary>
    /// Визиты в кабинете мастера: «1 визит», «2 визита», «5 визитов».
    /// </summary>
    Visits,
}
