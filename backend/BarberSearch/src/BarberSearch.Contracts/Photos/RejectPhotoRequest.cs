namespace BarberSearch.Contracts.Photos;

/// <summary>
/// Данные запроса на отказ в проверке фотографии: аватара пользователя или работы
/// в портфолио барбера.
/// </summary>
/// <remarks>
/// Одна форма на оба вида кадров: тело у отклонения аватара и фотографии портфолио
/// одинаковое, а различаются только маршрут и коды ошибок. Причина обязательна: отказ
/// без объяснения владелец не сможет исправить. Валидацию (не пустая после <c>Trim</c>,
/// не длиннее 500 символов) выполняет домен; коды —
/// <c>user.avatarModeration.reasonRequired</c> / <c>...reasonTooLong</c> для аватара и
/// <c>portfolioPhoto.moderation.reasonRequired</c> / <c>...reasonTooLong</c> для портфолио.
/// <para>
/// Текст причины — сообщение администратора владельцу кадра. В аудит он не попадает:
/// решение фиксируется полями самой сущности (<c>reviewed_by_user_id</c>,
/// <c>reviewed_at</c>, причина), а URL и причины в логи не пишутся.
/// </para>
/// </remarks>
/// <param name="Reason">Причина отказа; обрезается доменом по краям.</param>
public record RejectPhotoRequest(string? Reason);
