namespace BarberSearch.Application.Push.BookingStatus;

/// <summary>
/// Смена статуса записи, о которой клиенту нужно сообщить push-уведомлением.
/// </summary>
/// <remarks>
/// <para>
/// Событие создаёт и сотрудник салона (барбер профиля или администратор), и сам клиент.
/// Молчание — не признак автора, а признак <b>поверхности</b>: если клиент отменил или
/// перенёс запись в том же приложении, которое получило бы push, уведомление не создаётся —
/// экран уже подтвердил результат. С веба, кабинета и любой другой поверхности — создаётся
/// (AGENT.md §20.11). Гейт живёт в уведомителе, а не здесь: обработчики вызывают его всегда.
/// </para>
/// <para>
/// Значения явные (AGENT.md §10.10): они не попадают в базу напрямую, но служат стабильным
/// словарём для логов и тестов; в <c>PushNotificationKind</c> каждое из них отображается
/// один в один.
/// </para>
/// </remarks>
public enum BookingStatusChange
{
    /// <summary>
    /// Барбер или администратор подтвердил ожидающую бронь клиента.
    /// </summary>
    Confirmed = 1,

    /// <summary>
    /// Барбер или администратор отменил запись клиента.
    /// </summary>
    CancelledByBarber = 2,

    /// <summary>
    /// Барбер или администратор перенёс визит на другое время.
    /// </summary>
    RescheduledByBarber = 3,

    /// <summary>
    /// Клиент отменил запись сам; push создаётся, только если действие сделано не в приложении.
    /// </summary>
    CancelledByCustomer = 4,

    /// <summary>
    /// Клиент перенёс визит сам; push создаётся, только если действие сделано не в приложении.
    /// </summary>
    RescheduledByCustomer = 5
}
