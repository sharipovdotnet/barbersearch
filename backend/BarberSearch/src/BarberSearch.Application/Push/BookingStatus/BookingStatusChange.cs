namespace BarberSearch.Application.Push.BookingStatus;

/// <summary>
/// Смена статуса записи, о которой клиенту нужно сообщить push-уведомлением.
/// </summary>
/// <remarks>
/// <para>
/// Все три повода инициирует сотрудник салона — барбер профиля или администратор,
/// действующий как администратор, — а не сам клиент. Действие клиента
/// (<c>isClientOwner == true</c>) push не создаёт: он уже знает о нём, а мобильного
/// приложения для барбера нет, поэтому «уведомить исполнителя» нечего (AGENT.md §20.11).
/// </para>
/// <para>
/// Значения явные (AGENT.md §10.10): они не попадают в базу напрямую, но служат стабильным
/// словарём для логов и тестов; в <c>PushNotificationKind</c> каждое из них отображается
/// один в один.
/// </para>
/// </remarks>
public enum BookingStatusChange
{
    /// <summary>
    /// Барбер или администратор подтвердил ожидающую бронь клиента.
    /// </summary>
    Confirmed = 1,

    /// <summary>
    /// Барбер или администратор отменил запись клиента.
    /// </summary>
    CancelledByBarber = 2,

    /// <summary>
    /// Барбер или администратор перенёс визит на другое время.
    /// </summary>
    RescheduledByBarber = 3
}
