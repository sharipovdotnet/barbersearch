namespace BarberSearch.Application.Addresses;

/// <summary>
/// Что именно подсказывает провайдер: город или адрес внутри выбранного города.
/// </summary>
/// <remarks>
/// <para>
/// Значения явные (§10.10) и в БД не сохраняются: это часть запроса к внешнему провайдеру,
/// а не состояние домена. <c>City = 1</c> и <c>Address = 2</c> зафиксированы, чтобы будущий
/// кэш или журнал не поменяли смысл чисел при вставке нового варианта.
/// </para>
/// <para>
/// Два значения, а не одно: сначала человек выбирает город, и только потом адрес ищется
/// внутри него — иначе улицы приходят из всей страны.
/// </para>
/// </remarks>
public enum AddressSuggestionBound
{
    /// <summary>
    /// Подсказка города: только населённые пункты.
    /// </summary>
    City = 1,

    /// <summary>
    /// Подсказка адреса: улица и дом, при необходимости с фильтром по городу.
    /// </summary>
    Address = 2
}
