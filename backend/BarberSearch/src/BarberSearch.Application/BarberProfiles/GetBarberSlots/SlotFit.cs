namespace BarberSearch.Application.BarberProfiles.GetBarberSlots;

/// <summary>
/// Результат проверки «помещается ли визит в это время».
/// </summary>
/// <remarks>
/// Нужен ручной записи барбера: время, которое он вводит, не обязано совпадать с шагом
/// сетки (клиент мог прийти к 10:07), но визит обязан целиком лежать в рабочем дне
/// и не пересекаться ни с отпуском, ни с чужой бронью. Причина отказа важна для кода
/// ошибки: «вне расписания» и «время занято» — разные ответы.
/// </remarks>
public enum SlotFit
{
    /// <summary>Визит целиком помещается в свободное окно.</summary>
    Fits = 1,

    /// <summary>Время вне рабочего дня, до открытия, после закрытия или в отпуске.</summary>
    OutsideSchedule = 2,

    /// <summary>Время пересекается с активной бронью другого клиента.</summary>
    Overlap = 3
}
