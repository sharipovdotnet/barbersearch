namespace BarberSearch.Application.Abstractions;

/// <summary>
/// Поверхность, с которой пришёл запрос на изменение брони.
/// </summary>
/// <remarks>
/// <para>
/// Абстракция живёт в Application, а реализация — в Web: слой Application не ссылается на
/// ASP.NET Core и не знает ни про <c>HttpContext</c>, ни про заголовки. Признак нужен только
/// для решения «создавать ли push-строку»: действие, сделанное в том же приложении, которое
/// получило бы уведомление, push не создаёт — экран уже подтвердил результат, а сообщение
/// придёт после действия. Действие с другой поверхности (веб, кабинет барбера, админка,
/// неизвестный клиент) уведомляет.
/// </para>
/// <para>
/// Отсутствие признака — это «другая поверхность»: молчание включается только по явному
/// <c>X-Client-Surface: app</c>. Поэтому старый клиент и любой инструмент без заголовка
/// продолжают получать уведомления, а неизвестное значение не является ошибкой запроса
/// (AGENT.md §20.11).
/// </para>
/// </remarks>
public interface IClientSurface
{
    /// <summary>
    /// Запрос пришёл из мобильного приложения (<c>X-Client-Surface: app</c>).
    /// </summary>
    bool IsMobileApp { get; }
}
