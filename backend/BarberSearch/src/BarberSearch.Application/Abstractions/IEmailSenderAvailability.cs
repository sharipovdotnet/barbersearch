namespace BarberSearch.Application.Abstractions;

/// <summary>
/// Готовность почтового транспорта: настроена ли отправка на этом сервере.
/// </summary>
/// <remarks>
/// <para>
/// Отдельный порт от <see cref="IEmailSender"/>: обработчикам запроса нужен только признак
/// «почта настроена» (иначе <c>409 …unavailable</c>), а отправлять они больше не должны —
/// письмо уходит через outbox. Транспорт реализует оба интерфейса одной регистрацией.
/// </para>
/// <para>
/// Пустая секция <c>Email</c> — нормальное состояние: приложение работает, регистрация
/// отвечает <c>201</c>, а запрос письма — <c>409</c>.
/// </para>
/// </remarks>
public interface IEmailSenderAvailability
{
    /// <summary>
    /// Настроен ли транспорт: есть хост, порт и валидный адрес отправителя.
    /// </summary>
    bool IsAvailable { get; }
}
