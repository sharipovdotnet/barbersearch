namespace BarberSearch.Application.Bookings;

/// <summary>
/// Скоуп списка записей барбера: ближайшие визиты или история.
/// </summary>
/// <remarks>
/// Границу между скоупами задаёт время, а не статус: активная бронь, у которой
/// <c>EndAt</c> уже прошёл, попадает в историю, а завершённая — никогда в «ближайшие».
/// Направление keyset-пагинации тоже зависит от скоупа, поэтому оно не выводится
/// из данных страницы, а передаётся в репозиторий вместе с ней.
/// </remarks>
public enum BarberBookingScope
{
    /// <summary>Активные брони, которые ещё не закончились; ближайшая первой.</summary>
    Upcoming = 0,

    /// <summary>Завершённые, отменённые, неявки и прошедшие активные; свежие сверху.</summary>
    Past = 1
}
