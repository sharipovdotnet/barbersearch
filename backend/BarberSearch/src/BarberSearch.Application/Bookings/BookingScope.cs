namespace BarberSearch.Application.Bookings;

/// <summary>
/// Скоуп списка броней клиента: все, ближайшие визиты или история.
/// </summary>
/// <remarks>
/// Не путать с <see cref="BarberBookingScope"/>: там значение по умолчанию — «ближайшие»,
/// потому что кабинет барбера открывается на них, а здесь по умолчанию нужно прежнее
/// поведение <c>all</c>: админский фильтр по <c>userId</c> и внешние клиенты получают
/// полный список, пока явно не попросят вкладку.
/// <para>
/// Границу между скоупами задаёт время окончания, а не начало: визит, который уже начался,
/// но ещё не закончился, остаётся в «ближайших», а терминальный статус всегда в истории.
/// Направление keyset-пагинации зависит от скоупа, поэтому оно передаётся в репозиторий
/// вместе с ним и не выводится из данных страницы.
/// </para>
/// </remarks>
public enum BookingScope
{
    /// <summary>Все брони в порядке <c>start_at DESC, id</c> — поведение по умолчанию.</summary>
    All = 0,

    /// <summary>Активные брони, которые ещё не закончились; ближайшая первой.</summary>
    Upcoming = 1,

    /// <summary>Завершённые, отменённые, неявки и прошедшие активные; свежие сверху.</summary>
    Past = 2
}
