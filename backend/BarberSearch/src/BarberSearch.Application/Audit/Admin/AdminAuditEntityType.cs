namespace BarberSearch.Application.Audit.Admin;

/// <summary>
/// Тип сущности в фильтре журнала изменений.
/// </summary>
/// <remarks>
/// Значения повторяют allowlist <c>AuditTrail</c>: <c>User</c>, <c>BarberProfile</c>,
/// <c>PortfolioPhoto</c>, <c>Review</c>, <c>Salon</c>, <c>HairService</c>,
/// <c>Specialization</c> и <c>Booking</c>. У брони аудируются только изменения статуса и
/// заметки барбера — создание брони строки не пишет. <see cref="PortfolioPhoto"/> — ребёнок
/// профиля, но отдельный тип: загрузка и удаление кадра это жизненный цикл контента.
/// <see cref="All"/> — отсутствие фильтра.
/// </remarks>
public enum AdminAuditEntityType
{
    /// <summary>
    /// Без фильтра: все типы, которые аудируются.
    /// </summary>
    All = 0,

    /// <summary>
    /// Пользователь: роль, доступ, подтверждения, email, профиль барбера.
    /// </summary>
    User = 1,

    /// <summary>
    /// Профиль барбера: грейд, активность, подтверждение, рейтинг.
    /// </summary>
    BarberProfile = 2,

    /// <summary>
    /// Отзыв: публикация, рейтинг, текст.
    /// </summary>
    Review = 3,

    /// <summary>
    /// Салон: имя, адрес, город, индекс, страна, часовой пояс, координаты, контакты,
    /// активность.
    /// </summary>
    Salon = 4,

    /// <summary>
    /// Услуга каталога: имя, описание, категория, длительность по умолчанию, активность.
    /// </summary>
    HairService = 5,

    /// <summary>
    /// Специализация: имя, описание, активность.
    /// </summary>
    Specialization = 6,

    /// <summary>
    /// Бронь: только изменения статуса и заметки барбера. Создание брони не аудируется.
    /// </summary>
    Booking = 7,

    /// <summary>
    /// Фотография портфолио: профиль, файл, подпись, порядок, публикация, блокировка,
    /// статус проверки. Ребёнок профиля, но отдельный тип: загрузка и удаление кадра —
    /// действие с контентом, а не техническая правка профиля.
    /// </summary>
    PortfolioPhoto = 8
}
