namespace BarberSearch.Domain.Push;

/// <summary>
/// Состояние доставки push-уведомления.
/// </summary>
/// <remarks>
/// <para>
/// Собственное перечисление канала, а не переиспользование
/// <c>BarberNotificationDelivery</c>: у push и у Telegram-инбокса разные получатели, разные
/// причины пропуска и разные транспорты. Совпадающая семантика (0 — ожидание, 1/2/3 —
/// терминальные состояния) намеренная: миграция и индексы читаются одинаково, но изменение
/// одного канала не задевает другой.
/// </para>
/// <para>
/// <see cref="Pending"/> = 0 — значение по умолчанию и единственное состояние, из которого
/// возможны переходы. Повторная попытка не создаёт отдельного состояния: пока
/// <c>PushNotification.DeliveryAttempts</c> меньше предела, строка остаётся
/// <see cref="Pending"/> и лишь получает новый <c>NextAttemptAt</c>.
/// </para>
/// </remarks>
public enum PushDelivery
{
    /// <summary>
    /// Ожидает доставки; единственное состояние, допускающее переход.
    /// </summary>
    Pending = 0,

    /// <summary>
    /// Принято хотя бы одним устройством пользователя.
    /// </summary>
    Sent = 1,

    /// <summary>
    /// Доставка не нужна или невозможна: визит отменён или перенесён, окно закрылось,
    /// у пользователя нет устройств, push не настроен.
    /// </summary>
    Skipped = 2,

    /// <summary>
    /// Доставка окончательно не удалась: исчерпаны попытки.
    /// </summary>
    Failed = 3
}
