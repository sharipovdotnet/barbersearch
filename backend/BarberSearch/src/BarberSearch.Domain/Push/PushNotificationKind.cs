namespace BarberSearch.Domain.Push;

/// <summary>
/// Вид push-уведомления клиенту.
/// </summary>
/// <remarks>
/// <para>
/// Значения явные (AGENT.md §10.10) и попадают в базу как <c>smallint</c>: по ним построен
/// уникальный индекс <c>(booking_id, kind, start_at)</c>, поэтому числовые значения менять
/// нельзя. Напоминание, событие создания и события статуса одной брони сосуществуют; два
/// события одного вида на одно и то же время — уже дубль. Перенос может повториться, и
/// каждый новый целевой момент — отдельное событие (<c>start_at</c> входит в ключ).
/// </para>
/// <para>
/// Вид определяет и текст, и правило перепроверки перед доставкой: напоминание требует
/// <c>Confirmed</c>, событие создания доставляется и для <c>Pending</c> самозаписи клиента,
/// а события статуса — только пока визит жив и время не наступило (AGENT.md §20).
/// </para>
/// <para>
/// Действие самого клиента создаёт уведомление, если оно сделано <b>не в приложении</b>:
/// на телефоне экран уже подтвердил результат, а push пришёл бы после действия. Поэтому
/// клиентские отмена и перенос (7 и 8) существуют для веба и других поверхностей, а
/// приложение вместо push получает письмо (AGENT.md §20.11).
/// </para>
/// </remarks>
public enum PushNotificationKind
{
    /// <summary>
    /// Напоминание за <c>Push:ReminderLeadMinutes</c> до подтверждённого визита.
    /// </summary>
    Reminder = 1,

    /// <summary>
    /// Клиент записался сам: бронь создана публичным путём (<c>CreateBookingHandler</c> без
    /// <c>CustomerId</c> и без гостевых полей). Бронь при этом ещё <c>Pending</c>.
    /// </summary>
    BookingCreatedByCustomer = 2,

    /// <summary>
    /// Барбер записал клиента вручную: <c>CreateBookingCommand.CustomerId</c> задан либо
    /// передан гость. Бронь создаётся сразу <c>Confirmed</c>.
    /// </summary>
    BookingCreatedByBarber = 3,

    /// <summary>
    /// Барбер (или администратор как сотрудник) подтвердил ожидающую бронь клиента:
    /// <c>Pending</c> → <c>Confirmed</c> через <c>ConfirmBookingHandler</c>.
    /// </summary>
    BookingConfirmed = 4,

    /// <summary>
    /// Барбер или администратор отменил запись клиента. Отмена самим клиентом push не создаёт:
    /// он уже знает о своём действии, а мобильного приложения для барбера нет.
    /// </summary>
    BookingCancelledByBarber = 5,

    /// <summary>
    /// Барбер или администратор перенёс визит на другое время. <c>start_at</c> строки — новый
    /// момент: повторный перенос создаёт новое событие, даже если вид тот же.
    /// </summary>
    BookingRescheduledByBarber = 6,

    /// <summary>
    /// Клиент отменил запись сам с другой поверхности, а не в мобильном приложении: веб,
    /// кабинет или инструмент без признака поверхности. Отмена из приложения push не создаёт.
    /// </summary>
    BookingCancelledByCustomer = 7,

    /// <summary>
    /// Клиент перенёс визит сам с другой поверхности. <c>start_at</c> строки — новый момент,
    /// поэтому повторный перенос снова создаёт событие. Перенос из приложения push не создаёт.
    /// </summary>
    BookingRescheduledByCustomer = 8
}
