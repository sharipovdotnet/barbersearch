namespace BarberSearch.Domain.Salons;

/// <summary>
/// Вид места приёма: от обычного барбершопа до выезда к клиенту.
/// </summary>
/// <remarks>
/// Тип места не выводится из <see cref="Salon.IsListed"/> и наоборот: кабинет одного мастера
/// бывает и публичным, и скрытым. Тип описывает адрес и формат работы, а видимость в каталоге —
/// отдельный флаг <see cref="Salon.IsListed"/>.
/// <para>
/// Значения хранятся в <c>salons.kind</c> числами (как все сохраняемые перечисления, §10.10)
/// и проверяются ограничением <c>ck_salons_kind</c>.
/// </para>
/// </remarks>
public enum PlaceKind
{
    /// <summary>
    /// Обычный барбершоп со штатом мастеров.
    /// </summary>
    Salon = 1,

    /// <summary>
    /// Студия, которая сдаёт кресла другим барберам.
    /// </summary>
    RentalStudio = 2,

    /// <summary>
    /// Личный кабинет одного мастера.
    /// </summary>
    SoloStudio = 3,

    /// <summary>
    /// Приём клиентов на дому.
    /// </summary>
    Home = 4,

    /// <summary>
    /// Выезд к клиенту: в адресе хранится зона обслуживания, в городе — база.
    /// </summary>
    Mobile = 5
}
