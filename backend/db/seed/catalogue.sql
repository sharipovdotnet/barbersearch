-- Файл рассчитан на psql; запускать из backend/ после применения миграций:
--   psql -h 127.0.0.1 -p 5432 -U postgres -d barbersearch -f db/seed/catalogue.sql
--
-- Ожидаемый итог: 30 направлений, 68 услуг:
--   Стрижка 13, Борода 5, Окрашивание 28, Укладка 7, Уход 8, Другое 7.
--
-- ВАЖНО: файл пишет напрямую в БД и обходит API, поэтому audit_log не пополняется
-- и доменные проверки не выполняются. Для боевой базы используйте админский каталог;
