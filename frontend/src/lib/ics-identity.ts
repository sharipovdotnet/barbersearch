/**
 * Детерминированный ключ идемпотентности события календаря.
 *
 * Ключ описывает идентичность события, а не его содержимое: сервер хранит
 * гостевые брони с уникальным `(barber_profile_id, idempotency_key)`, поэтому
 * повторная загрузка того же файла возвращает уже созданную бронь, а не создаёт
 * дубль. Чтобы это работало после перезагрузки, в другой вкладке, на другом
 * устройстве и при смене схемы, алгоритм обязан быть одним и тем же везде:
 * `crypto.subtle` здесь не подходит (на HTTP его нет, и ключ зависел бы от
 * контекста), а `Math.random()` дал бы новый ключ на каждый вызов. Поэтому
 * используется чистый расчёт над строкой — cyrb128. Это не криптография, а
 * идентичность: менять алгоритм можно только с осознанной миграцией, иначе
 * ранее перенесённые события импортируются повторно.
 *
 * 128 бит, а не 32: на тысячах событий 32-битная коллизия уже реальна, а при
 * совпадении ключа сервер вернёт чужую бронь — это хуже дубля. Для 128 бит
 * вероятность коллизии на 5000 событий пренебрежимо мала.
 */

/**
 * Четыре 32-битных состояния cyrb128, перемешанные между собой.
 *
 * Реализация намеренно повторяет канонический алгоритм: любое изменение
 * констант или порядка операций меняет все ключи и ломает идемпотентность уже
 * перенесённых записей.
 */
function cyrb128(value: string): [number, number, number, number] {
  let h1 = 1779033703
  let h2 = 3144134277
  let h3 = 1013904242
  let h4 = 2773480762

  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index)

    h1 = h2 ^ Math.imul(h1 ^ code, 597399067)
    h2 = h3 ^ Math.imul(h2 ^ code, 2869860233)
    h3 = h4 ^ Math.imul(h3 ^ code, 951274213)
    h4 = h1 ^ Math.imul(h4 ^ code, 2716044179)
  }

  h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067)
  h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233)
  h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213)
  h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179)

  return [
    (h1 ^ h2 ^ h3 ^ h4) >>> 0,
    (h2 ^ h1) >>> 0,
    (h3 ^ h1) >>> 0,
    (h4 ^ h1) >>> 0,
  ]
}

/** Группа из 8 hex-символов: беззнаковое 32-битное слово. */
function toHex(word: number): string {
  return word.toString(16).padStart(8, '0')
}

/**
 * Ключ идемпотентности события: `ics:` и 32 lowercase hex-символа (36 всего).
 *
 * Вход — `UID` и стабильный `RECURRENCE-ID` (или `null` для одиночного
 * события). Оба значения обрезаются; `null` и пустая строка для
 * `recurrenceId` — один и тот же вход. Пустой после `trim` `UID` — ошибка:
 * без него идентичность события неизвестна, и детерминированный ключ построить
 * нельзя. Разбор такие события пропускает (`noUid`), так что это лишь guard.
 */
export function icsIdempotencyKey(
  uid: string,
  recurrenceId: string | null
): string {
  const normalizedUid = uid.trim()

  if (normalizedUid === '') {
    throw new Error('Пустой UID события.')
  }

  const input = `${normalizedUid}\0${(recurrenceId ?? '').trim()}`
  const [h1, h2, h3, h4] = cyrb128(input)

  return `ics:${toHex(h1)}${toHex(h2)}${toHex(h3)}${toHex(h4)}`
}
