/**
 * Сигнал «очереди админки изменились».
 *
 * Счётчики рейла — один общий снимок сводки: он обновляется тиком раз в 30 секунд,
 * и ждать этого тика после публикации отзыва бессмысленно. Раздел, который только
 * что изменил очередь, объявляет об этом сам — провайдер сводки делает тихий
 * `refresh()`, и бейдж меняется в пределах секунды.
 *
 * Событие — `window`, а не реестр подписчиков: раздел и рейл живут в разных ветках
 * дерева, и глобальная шина не требует протаскивать колбэк через все экраны.
 * Вызывать `notifyAdminQueuesChanged()` можно только после успешной мутации,
 * меняющей счётчик: на поиск, фильтры и открытие карточек — нельзя.
 */
export const ADMIN_QUEUES_CHANGED_EVENT = 'admin:queues-changed'

export function notifyAdminQueuesChanged(): void {
  window.dispatchEvent(new Event(ADMIN_QUEUES_CHANGED_EVENT))
}
